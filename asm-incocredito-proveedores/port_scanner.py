def _scan_port(host: str, port: int, timeout: float = 1.5) -> dict[str, Any] | None:
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.settimeout(timeout)
        result = s.connect_ex((host, port))
        s.close()
        if result == 0:
            service = SERVICE_MAP.get(port, "unknown")
            return {"port": port, "service": service, "state": "open"}
    except Exception:
        pass
    return None


def scan_ports(host: str, ports: list[int] | None = None,
               max_workers: int = 500, timeout: float = 1.5) -> list[dict[str, Any]]:
    ports_to_scan = ports or COMMON_PORTS
    found: list[dict[str, Any]] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as ex:
        futures = {ex.submit(_scan_port, host, p, timeout): p for p in ports_to_scan}
        for future in concurrent.futures.as_completed(futures):
            result = future.result()
            if result:
                found.append(result)
    found.sort(key=lambda x: x["port"])
    return found
